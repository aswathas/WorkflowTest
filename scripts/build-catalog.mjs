function slug(text) {
  const words = text
    .toLowerCase()
    .replace(/[`*_]/g, '')
    .replace(/[^a-z0-9\s-]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
  const kept = [];
  for (const w of words) {
    if (STOP.has(w) && kept.length) continue;
    kept.push(w);
  }
  return kept.slice(0, 6).join('-');
}

function parseCatalog() {
  const md = readFileSync(join(ROOT, 'CATALOG.md'), 'utf8');
  const phases = [];
  let cur = null;
  for (const line of md.split(/\r?\n/)) {
    const ph = line.match(/^## Phase (\d\d) — (.+)$/);
    if (ph) {
      cur = { num: ph[1], title: ph[2].trim(), lessons: [], module: null };
      phases.push(cur);
      continue;
    }
    const ls = line.match(/^(\d+)\. (.+)$/);
    if (ls && cur) {
      const title = ls[2]
        .replace(/\*\*/g, '')
        .replace(/\*([^*]+)\*/g, '$1')
        .replace(/←.*$/, '')
        .trim();
      cur.lessons.push({ num: Number(ls[1]), title, bold: ls[2].includes('**') });
      continue;
    }
    const mod = line.match(/^> \*\*Module (\d\d\.\d)\*\* — (.+)$/);
    if (mod && cur) cur.module = { id: mod[1], title: mod[2].trim() };
  }
  return phases;
}

function parseModules() {
  const md = readFileSync(join(ROOT, 'PRACTICE.md'), 'utf8');
  const out = [];
  for (const line of md.split(/\r?\n/)) {
    const m = line.match(/^\| (\d\d\.\d) \| (\d\d) \| (.+?) \| (\w+) \|$/);
    if (m) out.push({ id: m[1], phase: m[2], title: m[3], type: m[4] });
  }
  return out;
}

function lessonDoc(phase, lesson, prior) {
  const p = String(phase.num).padStart(2, '0');
  const intent = PHASE_INTENT[phase.num] ?? '';
  const grounding = prior.length
    ? prior.slice(-3).map((n) => `Lesson ${n}`).join(', ')
    : 'nothing — this lesson is the ground for its phase';
  return `# ${lesson.title}

> ${lesson.bold ? 'A load-bearing lesson.' : ''} One line, filled in by the author: what is
> different after this lesson that wasn't before.

**Type:** Learn
**Prerequisites:** ${grounding}
**Time:** ~30 minutes

<!-- scaffold generated by scripts/build-catalog.mjs — author this to LESSON-TEMPLATE.md.
     Phase intent: ${intent} -->

## Learning Objectives

- Write three "you will be able to DO this" lines, each starting with a verb
- Name the single reframe this lesson lands
- State the observable pass criterion for every exercise

## The Problem

Open with consequence, not definition. What breaks, what it costs, what happens
if the reader doesn't have this. One sentence of real pain.

## The Concept

The idea itself. Mermaid diagram for anything with flow or structure.
Named the way people actually name it.

**The reframe:** << ONE SENTENCE — the thing that makes it click. >>

## Build It

Numbered steps the reader runs. Every step ends with something they can observe.

## Use It

| Command or concept | When you reach for it |
|---|---|
| TODO | TODO |

## Exercises

1. Do the thing
   ✅ You pass when <the observable state that means it worked.>

## Key Terms

| Term | What people say | What it actually means |
|------|-----------------|------------------------|
| TODO | "the wrong intuition" | the accurate definition |
`;
}

function quizJson(lesson, siblings) {
  const others = siblings.filter((s) => s.num !== lesson.num);
  const opts = [lesson.title, ...others.slice(0, 3).map((s) => s.title)];
  return JSON.stringify(
    {
      lesson: lesson.num,
      title: lesson.title,
      questions: [
        {
          id: `${lesson.num}-grounding`,
          prompt:
            `You are about to use the idea in "${lesson.title}". ` +
            'Which earlier lesson in this phase established the concept it leans on?',
          options: opts,
          answer: 0,
          explanation:
            'Grounding before leaning. An ungrounded concept is the single biggest reason a reader falls off.',
        },
      ],
    },
    null,
    2,
  ) + '\n';
}

const BRIEF = (m) => `# ${m.id} — ${m.title}

**Type:** ${m.type}
**Phase:** ${m.phase}

## The task

State the artifact in one sentence, in the learner's words: what will exist when
this is done.

## The constraint that makes it non-trivial

One constraint. The thing that stops this being a tutorial. It must force a
trade-off the learner has to defend.

## What is out of scope

Name one thing this module deliberately does not cover, and when to come back
to it. Silence reads as oversight.

## Done means

The rubric's criteria are met **and** the learner can explain the mechanism with
the code closed.
`;

const RUBRIC = (m) => `# ${m.id} — Rubric

**Type:** ${m.type}

A module is not done when the code runs. It is done when every criterion below
is observable and the learner can explain the mechanism.

## Observable criteria

- [ ] The artifact exists at the agreed path and runs from a clean shell
- [ ] The stated constraint was honoured — name how you know
- [ ] Something in the artifact was broken on purpose and recovered from
- [ ] The learner can state the trade-off they made and why

## Proof-of-understanding questions

Answer these with the artifact closed. Being unable to answer is the signal to
redo the module, not to re-read the lesson.

1. What breaks if this design choice is different?
2. Which part was hardest, and what did you do when you got stuck?
3. If you ran this again tomorrow, what would you change first?
`;

function writeIfMissing(path, content, stats) {
  if (existsSync(path)) {
    stats.skipped++;
    return false;
  }
  if (!DRY) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  stats.written++;
  return true;
}

const stats = { written: 0, skipped: 0 };
const phases = parseCatalog();
const modules = parseModules();

for (const phase of phases) {
  const phaseSlug = `${phase.num}-${slug(phase.title)}`;
  let prior = [];
  for (const lesson of phase.lessons) {
    const dir = join(ROOT, 'phases', phaseSlug, `${String(lesson.num).padStart(2, '0')}-${slug(lesson.title)}`);
    writeIfMissing(join(dir, 'docs', 'en.md'), lessonDoc(phase, lesson, prior), stats);
    writeIfMissing(join(dir, 'quiz.json'), quizJson(lesson, phase.lessons), stats);
    prior.push(lesson.num);
  }
  phase.dir = phaseSlug;
}

for (const m of modules) {
  const phase = phases.find((x) => x.num === m.phase);
  if (!phase) continue;
  const dir = join(ROOT, 'practice', `${m.id}-${slug(m.title)}`);
  writeIfMissing(join(dir, 'BRIEF.md'), BRIEF(m), stats);
  writeIfMissing(join(dir, 'RUBRIC.md'), RUBRIC(m), stats);
}

const lessonCount = phases.reduce((n, p) => n + p.lessons.length, 0);
console.log(
  DRY
    ? `[dry] would write ${stats.written}, skip ${stats.skipped} — ${lessonCount} lessons across ${phases.length} phases, ${modules.length} modules`
    : `wrote ${stats.written} file(s), skipped ${stats.skipped} existing — ${lessonCount} lessons across ${phases.length} phases, ${modules.length} modules`,
);