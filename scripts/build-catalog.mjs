  '03': 'What actually costs money, and which model the job actually needs.',
  '04': 'The tool itself, and the one concept everything else hangs on: the agentic loop.',
  '05': 'The most flexible extension layer — packaging repeatable instructions.',
  '06': 'Context isolation. A separate window is the reason parallelism works.',
