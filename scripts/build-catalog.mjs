#!/usr/bin/env node
// build-catalog.mjs — materialize every lesson and module named in CATALOG.md /
// PRACTICE.md, so a parallel authoring workflow has a real tree to fill.
//
// Single source of truth is the catalog itself. This script never invents a
// lesson the catalog doesn't list, and never overwrites authored content.
//
// Usage:  node scripts/build-catalog.mjs [--dry]
// Then:   node scripts/validate-lessons.mjs

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const DRY = process.argv.includes('--dry');

const STOP = new Set(['a', 'an', 'the', 'and', 'of', 'to', 'in', 'on', 'for', 'is', 'are', 'it', 'its', 'when', 'why', 'how', 'what', 'not', 'no', 'from', 'at', 'by', 'with', 'as']);

// Phase teaching intent. One line per phase; becomes the "what this phase is for"
// context that every lesson scaffold carries so authors don't re-invent it.
